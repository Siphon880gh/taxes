function unk(next: string[], label = "I don't know"): Answer {
  return { id: "unknown", label, edge: "Unknown", next };
}

function choice(
  id: string,
  label: string,
  next: string[],
  edge?: string,
): Answer {
  return { id, label, edge: edge ?? label, next };
}

export function freeEntry(node: GraphNode): { answerId: string; next: string[]; edge?: string } | null {
  return node.numberInputs ?? node.textInput ?? null;
}

